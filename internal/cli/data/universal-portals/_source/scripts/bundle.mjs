// Builds the single file the Auth0 CLI embeds: the setup and audit tool and its dependencies in one
// ES module that `node` can run. Run it with `npm run bundle`, which compiles first so the hash
// code is current. The output is generated: change the sources and run this again.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

import { sourceHash } from "../dist/src/source-hash.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const outfile = fileURLToPath(new URL("../../universal-portals.mjs", import.meta.url));

await build({
  absWorkingDir: root,
  entryPoints: ["src/cli.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile,
  legalComments: "none",
  logLevel: "warning",
  banner: {
    js: [
      '// Generated by "npm run bundle" in the _source folder. Do not edit.',
      `// source-sha256: ${sourceHash(root)}`,
      // Some dependencies still call require(), which an ES module does not have.
      'import { createRequire } from "node:module";',
      "const require = createRequire(import.meta.url);",
    ].join("\n"),
  },
});
